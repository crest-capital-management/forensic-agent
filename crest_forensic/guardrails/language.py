"""Banned-language guardrail (Build Plan section 9, rules 2-3 in section 2).

The tool describes; it never concludes and never blames. Any flag whose text
contains one of these is dropped and logged, even though the text is
generated by our own code — this stops a future wording change from drifting.
"""
from __future__ import annotations

import re

_BANNED = [
    r"fraud\w*", r"committed", r"guilty", r"criminal\w*", r"embezzl\w*", r"misappropriat\w*",
    r"cooked", r"fake\w*", r"fabricat\w*", r"theft", r"stole\w*", r"crook\w*", r"scam\w*",
]
_PATTERN = re.compile(r"\b(" + "|".join(_BANNED) + r")\b", re.IGNORECASE)

LEADS_NOT_PROOF = (
    "Statistical lead only: most anomalies have innocent explanations. "
    "Public data cannot show the reason."
)
PUBLIC_DATA_LIMIT = (
    "Based only on public-domain figures as saved from the sources named in the citation; "
    "no non-public information is held or implied."
)


def banned_terms_in(*texts: str) -> list[str]:
    found = []
    for t in texts:
        found += [m.group(0).lower() for m in _PATTERN.finditer(t or "")]
    return sorted(set(found))
