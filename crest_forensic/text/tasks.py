def prompt_sha256() -> str:
    material = json.dumps(
        {"version": PROMPT_VERSION, "system": SYSTEM_PROMPT,
         "tasks": {k: {"d": t.description, "f": t.finding_types} for k, t in sorted(TASKS.items())}},
        sort_keys=True)
    return hashlib.sha256(material.encode("utf-8")).hexdigest()


def build_user_message(task: TextTask, basis: str, fiscal_year: str, pages: dict[int, str]) -> str:
    types = "\n".join(f"- {name}: {definition}" for name, definition in task.finding_types.items())
    body = "\n".join(f'<page number="{n}">\n{pages[n]}\n</page>' for n in sorted(pages))
    return (
        f"TASK: {task.name} ({task.check_id}) for the {basis} financial statements, financial year {fiscal_year}.\n"
        f"{task.description}\n\n"
        f"ALLOWED FINDING TYPES:\n{types}\n\n"
        "Read the pages below and report findings with the report_findings tool.\n\n"
        f"<untrusted_document>\n{body}\n</untrusted_document>"
    )
